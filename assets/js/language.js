const languageSelect = document.querySelector('#language-select');
const navToggle = document.querySelector('.nav-toggle');
const siteNav = document.querySelector('.site-nav');
const description = document.querySelector('meta[name="description"]');
const textWalker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
const pageTextNodes = [];

while (textWalker.nextNode()) {
	const textNode = textWalker.currentNode;
	if (textNode.parentElement.closest('script, style, select, code')) continue;
	pageTextNodes.push({ node: textNode, original: textNode.nodeValue });
}

function setLanguage(language) {
	const isSomali = language === 'so';
	document.documentElement.lang = language;
	pageTextNodes.forEach(({ node, original }) => {
		if (!isSomali) {
			node.nodeValue = original;
			return;
		}

		const text = original.trim();
		const translation = somaliTranslations[text];
		if (!translation) return;
		const leadingSpace = original.match(/^\s*/)[0];
		const trailingSpace = original.match(/\s*$/)[0];
		node.nodeValue = `${leadingSpace}${translation}${trailingSpace}`;
	});

	document.title = isSomali
		? 'Abdirahman Osman Siyad | Injineer Batrool iyo Falanqeeye Xogeed'
		: 'Abdirahman Osman Siyad | Petroleum Engineer & Data Analyst';
	description.content = isSomali
		? 'Abdirahman Osman Siyad waa Injineer Batrool iyo Falanqeeye Xogeed ka shaqeeya injineernimada dhulka hoose, kaydinta xogta, iyo falanqaynta hawlgalka.'
		: 'Abdirahman Osman Siyad is a Petroleum Engineer and Data Analyst working across subsurface engineering, data warehousing, and operational analytics.';
	languageSelect.value = language;
	languageSelect.setAttribute('aria-label', isSomali ? 'Dooro luqadda' : 'Choose language');
	siteNav.setAttribute('aria-label', isSomali ? 'Hagidda ugu weyn' : 'Main navigation');
	navToggle.setAttribute('aria-label', isSomali ? 'Fur hagidda' : 'Open navigation');
	try {
		localStorage.setItem('portfolio-language', language);
	} catch {
		// The selection still works when browser storage is unavailable.
	}
}

languageSelect.addEventListener('change', () => setLanguage(languageSelect.value));

let savedLanguage = 'en';
try {
	const storedLanguage = localStorage.getItem('portfolio-language');
	if (storedLanguage === 'so') savedLanguage = storedLanguage;
} catch {
	// Use English when browser storage is unavailable.
}
setLanguage(savedLanguage);